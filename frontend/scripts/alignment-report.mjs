// Builds ALIGNMENT_AUDIT.md from the measurements written by e2e/audit.spec.ts.
import fs from 'node:fs'
import path from 'node:path'
const dir = path.resolve(import.meta.dirname, '../../audit-screenshots/landing')
const fixes = JSON.parse(fs.readFileSync(path.resolve(import.meta.dirname, 'alignment-fixes.json'), 'utf8'))
const labels = fs.readdirSync(dir).filter((f) => f.startsWith('alignment-')).map((f) => f.slice(10, -5))
const order = (l) => parseInt(l, 10) + (l.includes('landscape') ? 0.5 : 0)
labels.sort((a, b) => order(a) - order(b))
let md = `# Landing Alignment Audit

Generated by \`frontend/scripts/alignment-report.mjs\` from measurements taken by
\`frontend/e2e/audit.spec.ts\` (Playwright, Chrome, production build). Every grid cell's left and
right edges are compared with the computed column lines of its grid (tolerance 1px), every
\`data-align="start"\` element with its container's content edge, and every container (header,
sections, footer) with every other. Screenshots for each width are in \`audit-screenshots/landing/<width>/\`.

## Summary

| Viewport | Container content edges (left, right) | Cells measured | Off grid | Other problems |
| :-- | :-- | --: | --: | --: |
`
const details = []
for (const l of labels) {
  const a = JSON.parse(fs.readFileSync(path.join(dir, `alignment-${l}.json`), 'utf8'))
  const off = a.rows.filter((r) => !r.ok).length
  md += `| ${l} | ${a.edges.map((e) => e.replace('|', ', ')).join(' / ')} | ${a.rows.length} | ${off} | ${a.problems.length - off} |\n`
  if (['360', '768', '1440'].includes(l)) {
    details.push(`### ${l}px\n\n| Section | Cell spans (d / t / m) | First text | Left | Right | Columns | On grid |\n| :-- | :-- | :-- | --: | --: | :-- | :-: |\n` +
      a.rows.map((r) => `| ${r.section} | ${r.cell.replaceAll('|', ' , ')} | ${r.text.replaceAll('|', '/') || '(visual)'} | ${r.left} | ${r.right} | ${r.colStart} to ${r.colEnd} | ${r.ok ? 'yes' : 'NO'} |`).join('\n'))
  }
}
md += `\n## Cell measurements (360, 768 and 1440)\n\n${details.join('\n\n')}\n\n## Issues found during the audit\n\nEvery item below was found by the screenshot review or the automated checks and is fixed.\n\n| # | Viewport | Issue | Fix | Status |\n| :-: | :-- | :-- | :-- | :-- |\n`
fixes.forEach((f, i) => (md += `| ${i + 1} | ${f.where} | ${f.issue} | ${f.fix} | Fixed |\n`))
fs.writeFileSync(path.resolve(import.meta.dirname, '../../ALIGNMENT_AUDIT.md'), md)
console.log(`wrote ALIGNMENT_AUDIT.md (${labels.length} viewports)`)
